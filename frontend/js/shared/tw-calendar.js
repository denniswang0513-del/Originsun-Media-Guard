/** ISO 日期（可帶時間）→ 'YYYY-MM-DD'；認不出來回空字串。 */
export function isoDay(value) {
    const s = String(value || "").trim();
    return /^\d{4}-\d{2}-\d{2}/.test(s) ? s.substring(0, 10) : "";
}

/**
 * 日期 → {day, wd, weekend, holiday}。
 * 🔴 用 UTC 建 Date：只給 'YYYY-MM-DD' 時 JS 會當 UTC 午夜解析，若再用本地
 * getDay() 讀，台北以西的時區會整個差一天。用 getUTCDay() 才與字面日期一致。
 */
export function dayMark(value) {
    const day = isoDay(value);
    if (!day) {
        return { day: "", wd: "", weekend: false, holiday: "" };
    }
    const idx = (new Date(day + "T00:00:00Z").getUTCDay() + 6) % 7;   // 0=一 … 6=日
    return {
        day,
        wd: WD[idx],
        weekend: idx >= 5,
        holiday: TW_HOLIDAYS[day] || "",
    };
}

/** 列表用的小標籤 class（沒有就回空字串，呼叫端直接串進 class 屬性）。 */
export function dayClass(value) {
    const m = dayMark(value);
    if (m.holiday) { return "is-holiday"; }
    return m.weekend ? "is-weekend" : "";
}
